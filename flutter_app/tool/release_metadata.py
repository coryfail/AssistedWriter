#!/usr/bin/env python3
"""Create signed-updater feeds and the metadata needed by legacy Mac clients.

Signatures are generated by Sparkle/WinSparkle before invoking this script.
This script does not generate, read, or publish private signing keys.
"""
import argparse
import base64
import datetime
import hashlib
import json
from pathlib import Path
from urllib.parse import quote
import xml.etree.ElementTree as ET


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version', required=True)
    parser.add_argument('--build-number', required=True, type=int)
    parser.add_argument('--base-url', required=True)
    parser.add_argument('--mac-archive', required=True, type=Path)
    parser.add_argument('--windows-installer', required=True, type=Path)
    parser.add_argument('--mac-signature', required=True)
    parser.add_argument('--windows-signature', required=True)
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    if not args.base_url.startswith('https://'):
        parser.error('The public artifact URL must use HTTPS.')
    if args.build_number < 1:
        parser.error('The build number must be positive and increase for every release.')
    for signature in [args.mac_signature, args.windows_signature]:
        try:
            if not base64.b64decode(signature, validate=True):
                raise ValueError('empty signature')
        except (ValueError, TypeError):
            parser.error('Updater signatures must be nonempty Base64 strings.')
    for artifact in [args.mac_archive, args.windows_installer]:
        if not artifact.is_file():
            parser.error(f'Artifact does not exist: {artifact}')
    sparkle = 'http://www.andymatuschak.org/xml-namespaces/sparkle'
    ET.register_namespace('sparkle', sparkle)
    rss = ET.Element('rss', {'version': '2.0'})
    channel = ET.SubElement(rss, 'channel')
    ET.SubElement(channel, 'title').text = 'Assisted Writer updates'
    now = datetime.datetime.now(datetime.timezone.utc)
    for platform, artifact, signature in [
        ('macos', args.mac_archive, args.mac_signature),
        ('windows', args.windows_installer, args.windows_signature),
    ]:
        item = ET.SubElement(channel, 'item')
        ET.SubElement(item, 'title').text = f'Assisted Writer {args.version}'
        ET.SubElement(item, 'pubDate').text = now.strftime('%a, %d %b %Y %H:%M:%S +0000')
        ET.SubElement(item, f'{{{sparkle}}}version').text = str(args.build_number) if platform == 'macos' else args.version
        ET.SubElement(item, f'{{{sparkle}}}shortVersionString').text = args.version
        ET.SubElement(item, 'enclosure', {
            'url': args.base_url.rstrip('/') + '/' + quote(artifact.name),
            'length': str(artifact.stat().st_size),
            'type': 'application/octet-stream',
            f'{{{sparkle}}}os': platform,
            f'{{{sparkle}}}{"edSignature" if platform == "macos" else "dsaSignature"}': signature,
        })
    args.out.mkdir(parents=True, exist_ok=True)
    ET.indent(rss)
    ET.ElementTree(rss).write(args.out / 'appcast.xml', encoding='utf-8', xml_declaration=True)
    mac_data = args.mac_archive.read_bytes()
    sha512 = base64.b64encode(hashlib.sha512(mac_data).digest()).decode('ascii')
    legacy = '\n'.join([
        f'version: {json.dumps(args.version)}', 'files:',
        f'  - url: {json.dumps(args.mac_archive.name)}', f'    sha512: {json.dumps(sha512)}',
        f'    size: {len(mac_data)}', f'path: {json.dumps(args.mac_archive.name)}',
        f'sha512: {json.dumps(sha512)}', f'releaseDate: {json.dumps(now.isoformat())}', '',
    ])
    (args.out / 'latest-mac.yml').write_text(legacy, encoding='utf-8')
    checksums = ''.join(f'{hashlib.sha256(artifact.read_bytes()).hexdigest()}  {artifact.name}\n'
                        for artifact in [args.mac_archive, args.windows_installer])
    (args.out / 'SHA256SUMS.txt').write_text(checksums, encoding='utf-8')


if __name__ == '__main__':
    main()
